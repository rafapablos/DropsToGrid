def _decode_bitmask(hex_str: str, height: int, width: int) -> torch.Tensor:
    packed = np.frombuffer(bytes.fromhex(hex_str), dtype=np.uint8)
    bits = np.unpackbits(packed)[: height * width].reshape(height, width)
    return torch.from_numpy(bits.astype(bool))


